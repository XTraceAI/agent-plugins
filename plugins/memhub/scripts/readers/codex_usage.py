"""Prefer persisted per-response usage over parallel UI token-meter snapshots.

The legacy conversion supplies record identities/order. Usage is overlaid only
from the first ledger entry onward, retaining any older legacy-only prefix.
"""
from __future__ import annotations

import uuid
from bisect import bisect_left, bisect_right
from . import codex, _parseable_timestamp


def apply(rows, records, sources, usage_targets, *, session_id, namespace, seen):
    ledgers = [(i, row) for i, row in enumerate(rows) if row.get('type') == 'token_usage_record']
    if not ledgers:
        return records
    first = ledgers[0][0]
    protected = {id(record) for i, record in usage_targets.items() if i < first}
    for i, record in usage_targets.items():
        if i >= first:
            record['message'].pop('usage', None)
    # Real assistant output, as opposed to generated legacy usage-only rows.
    assistants = [(sources[id(record)], record) for record in records
                  if record['type'] == 'assistant'
                  and rows[sources[id(record)]].get('type') == 'response_item']
    assistant_positions = [i for i, _ in assistants]
    legacy_only = [(i, record) for i, record in usage_targets.items()
                   if sources[id(record)] == i]
    legacy_positions = [i for i, _ in legacy_only]
    retained = {id(record) for record in records
                if sources[id(record)] < first
                or rows[sources[id(record)]].get('type') != 'event_msg'}
    previous = -1
    model = None
    context_position = 0
    for n, (position, ledger) in enumerate(ledgers):
        payload = ledger.get('payload')
        if not isinstance(payload, dict) or payload.get('thread_id') != session_id:
            raise ValueError('usage ledger belongs to another thread')
        response = payload.get('response_id')
        total = codex._usage_total(payload.get('usage'))
        if not isinstance(response, str) or not response.strip() or total is None:
            raise ValueError('usage ledger lacks a response identity or valid counters')
        if total['input_tokens'] < total['cached_input_tokens'] + total['cache_write_input_tokens']:
            raise ValueError('usage ledger cache counters exceed input tokens')
        stamp = ledger.get('timestamp')
        if stamp is not None and not _parseable_timestamp(stamp):
            raise ValueError('invalid usage ledger timestamp')
        key = (session_id, response)
        if key in seen:
            if seen[key] != total:
                raise ValueError('conflicting usage for one response')
            continue
        seen[key] = total
        response_start = previous
        for offset, row in enumerate(rows[context_position:position], context_position):
            value = row.get('payload', {})
            if row.get('type') == 'turn_context':
                model = value.get('model')
                response_start = offset
            elif (row.get('type') == 'response_item' and value.get('role') == 'user'
                  or row.get('type') == 'event_msg' and value.get('type') in ('task_started', 'task_complete')
                  or row.get('type') == 'event_msg' and value.get('type') == 'token_count'
                  and isinstance(value.get('info'), dict)
                  and codex._usage_total(value['info'].get('total_token_usage')) is not None):
                response_start = offset
        context_position = position
        at = bisect_left(assistant_positions, position) - 1
        target = None
        if at >= 0:
            source_position, candidate = assistants[at]
            if source_position > response_start and id(candidate) not in protected:
                target = candidate
        next_position = ledgers[n + 1][0] if n + 1 < len(ledgers) else len(rows)
        if target is None:
            # Reuse the existing usage-only identity when one was generated by
            # the parallel UI event for this response.
            at = bisect_right(legacy_positions, position)
            if at < len(legacy_only) and legacy_positions[at] < next_position:
                target = legacy_only[at][1]
        if target is None:
            target = {'type': 'assistant', 'uuid': str(uuid.uuid5(
                uuid.NAMESPACE_URL, f'memhub:codex:{namespace}:ledger-usage:{response}')),
                'message': {'role': 'assistant', 'content': []}}
            if stamp is not None:
                target['timestamp'] = stamp
            sources[id(target)] = position
            records.append(target)
        target['api_message_id'] = response
        target['requestId'] = response
        # Text, reasoning, and tool items emitted by one request share its
        # response identity. Keep the measurement on one target only, so
        # downstream completeness can fold fragments without double counting.
        for _, fragment in assistants[bisect_right(assistant_positions, response_start):
                                      bisect_left(assistant_positions, position)]:
            if id(fragment) not in protected:
                fragment['api_message_id'] = response
                fragment['requestId'] = response
        if model is None:
            target['message'].pop('model', None)
        else:
            target['message']['model'] = model
        usage = codex._usage_delta(total, None)
        # A measured zero is still an explicit measurement.
        target['message']['usage'] = usage or {
            'input_tokens': 0, 'output_tokens': 0,
            'cache_read_input_tokens': 0, 'cache_creation_input_tokens': 0}
        retained.add(id(target))
        previous = position
    return sorted((record for record in records if id(record) in retained),
                  key=lambda record: sources[id(record)])


def attach_reasoning(rows, records) -> None:
    """Copy each ledger response's reasoning count onto its record's usage.

    Runs after ``apply`` (which rewrites ledger-backed usage to the four
    counts) and never inside it: ``apply`` raises on anomalies by design,
    while a missing or malformed reasoning count must cost only itself. The
    caller still wraps this in its own ``try``. The count lands where Claude
    puts its own (``output_tokens_details.thinking_tokens``), which an older
    backend ignores.
    """
    reasoning = {}
    for row in rows:
        if not isinstance(row, dict) or row.get('type') != 'token_usage_record':
            continue
        payload = row.get('payload')
        if not isinstance(payload, dict):
            continue
        response, usage = payload.get('response_id'), payload.get('usage')
        count = usage.get('reasoning_output_tokens') if isinstance(usage, dict) else None
        if isinstance(response, str) and type(count) is int and count >= 0:
            reasoning[response] = count
    if not reasoning:
        return
    for record in records:
        if not isinstance(record, dict):
            continue
        count = reasoning.get(record.get('api_message_id'))
        message = record.get('message')
        if not count or not isinstance(message, dict) or not isinstance(message.get('usage'), dict):
            continue
        message['usage']['output_tokens_details'] = {'thinking_tokens': count}
